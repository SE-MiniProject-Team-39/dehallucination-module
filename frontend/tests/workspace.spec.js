import {test,expect} from '@playwright/test';

test('reviewer workspace verifies, overrides, audits and filters content', async({page})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');
  await page.getByLabel('Username',{exact:true}).fill('admin');
  await page.getByLabel('Password',{exact:true}).fill('wrong-password');
  await page.getByRole('button',{name:'Sign in →'}).click();
  await expect(page.getByRole('alert')).toBeVisible();
  await page.getByLabel('Password',{exact:true}).fill('browser-test-password');
  await page.getByRole('button',{name:'Sign in →'}).click();
  await expect(page.getByRole('heading',{name:'A second look. A clearer answer.'})).toBeVisible();
  const content=page.getByLabel('AI-generated text');
  const verifyButton=page.locator('button.primary').filter({hasText:'Verify content'});
  await content.fill('   ');
  await expect(verifyButton).toBeDisabled();
  await expect(page.getByText('3 / 10,000')).toBeVisible();
  await content.fill('😀'.repeat(5001));
  await expect(page.getByText('5,001 / 10,000')).toBeVisible();
  expect(await content.evaluate(el=>Array.from(el.value).length)).toBe(5001);
  const exactLimit='a'.repeat(9999)+'😀';
  await content.fill(exactLimit);
  await expect(page.getByText('10,000 / 10,000')).toBeVisible();
  expect(await content.evaluate(el=>Array.from(el.value).length)).toBe(10000);
  expect(await content.inputValue()).toBe(exactLimit);
  await content.fill(exactLimit+'😀');
  await expect(page.getByText('10,000 / 10,000')).toBeVisible();
  expect(await content.inputValue()).toBe(exactLimit);
  await content.fill('');
  await page.getByRole('button',{name:'Try an example'}).click();
  await page.route('**/api/verify',route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({error:{message:'Verification is temporarily unavailable.'}})}));
  await page.locator('button.primary').filter({hasText:'Verify content'}).click();
  await expect(page.getByRole('alert')).toContainText('Verification is temporarily unavailable.');
  await page.screenshot({path:'../docs/frontend-sprint1-error.png',fullPage:true});
  await page.unroute('**/api/verify');
  await page.locator('button.primary').filter({hasText:'Verify content'}).click();
  await expect(page.locator('.claim-row')).toHaveCount(4);
  await expect(page.locator('.highlight.supported')).toHaveCount(2);
  await expect(page.locator('.highlight.contradicted')).toHaveCount(1);
  await expect(page.locator('.highlight.unsupported')).toHaveCount(1);
  await page.locator('.claim-row').filter({hasText:'Australia'}).click();
  await expect(page.locator('.correction')).toContainText('Canberra');
  await expect(page.locator('.evidence-card a').first()).toHaveAttribute('href',/https:\/\//);
  await page.getByRole('button',{name:'Override verdict',exact:true}).click();
  await page.getByLabel('Verdict',{exact:true}).selectOption('Not-Checkable');
  await page.getByLabel('Reviewed confidence').fill('0.1');
  await page.getByLabel('Reason',{exact:true}).fill('Browser test reviewer requests further evidence.');
  await page.getByRole('button',{name:'Save review',exact:true}).click();
  await expect(page.locator('.override-note')).toContainText('Reviewed by admin');
  await expect(page.locator('.highlight.not-checkable')).toHaveCount(1);
  await page.getByRole('button',{name:'Approve review'}).click();
  await expect(page.getByRole('button',{name:'Approved by admin'})).toBeVisible();
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:'../docs/workspace.png',fullPage:true});
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:'Export JSON'}).click();
  expect((await downloadPromise).suggestedFilename()).toMatch(/dam-.*\.json/);
  await page.getByRole('button',{name:'Review history',exact:true}).click();
  await page.getByLabel('Search text').fill('no-such-text-unique');
  await page.getByRole('button',{name:'Apply filters'}).click();
  await expect(page.getByText('No verification jobs match your filters.')).toBeVisible();
  await page.getByRole('button',{name:'Analytics',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Hallucination score over time'})).toBeVisible();
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await page.getByRole('button',{name:'Save settings'}).click();
  await expect(page.getByRole('status')).toContainText('Policy saved and logged');
  await page.getByRole('button',{name:'Access & audit',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Audit trail'})).toBeVisible();
  await expect(page.locator('.audit-list')).toContainText('verdict override');
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
  await page.screenshot({path:'../docs/frontend-sprint1-mobile.png',fullPage:true});
  expect(errors).toEqual([]);
  await page.setViewportSize({width:1440,height:1000});
  await page.getByRole('button',{name:'Sign out'}).click();
  await expect(page.getByRole('heading',{name:'Open your workspace.'})).toBeVisible();
});
